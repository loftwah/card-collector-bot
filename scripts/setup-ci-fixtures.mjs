#!/usr/bin/env node
/**
 * Synthetic, local-only fixtures for the existing browser acceptance scripts.
 *
 * Run after `pnpm setup:local --skip-sources` in a fresh CI checkout. Artwork
 * comes from tracked Foilbury brand files; no launch manifest, sibling checkout,
 * provider key or network artwork import is used. The historical slugs/names
 * below are privacy-test sentinels, not imported characters or biographies.
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

const baseURL = process.env.FOILBURY_URL ?? "http://localhost:5173";
const target = new URL(baseURL);
assert.equal(process.env.CI, "true", "Synthetic fixture setup requires CI=true and a fresh CI checkout.");
assert.ok(
  target.protocol === "http:" &&
    ["localhost", "127.0.0.1"].includes(target.hostname) &&
    target.port === "5173" &&
    target.pathname === "/" &&
    !target.username && !target.password && !target.search && !target.hash,
  "Synthetic fixtures may only target the local server on port 5173.",
);

const response = await fetch(new URL("/api/v1/status", target), {
  redirect: "error",
  signal: AbortSignal.timeout(10000),
});
assert.ok(response.ok, `Local status returned ${response.status}; run setup:local --skip-sources first.`);
const status = await response.json();
assert.equal(status.name, "Foilbury");
assert.equal(status.environment, "local", "Synthetic fixtures require the local Worker environment.");
assert.equal(status.local, true);
assert.equal(status.dev_login, true);
assert.equal(status.configured, true);
assert.equal(status.tenant, "cabinet");
assert.ok(status.providers && Object.values(status.providers).every((enabled) => enabled === false), "CI fixtures require every external provider to be disabled.");

// Import only after validating the target: these helpers can start a local
// server and read the scoped credentials generated by setup:local.
const { apiForm, apiJson } = await import("./lib/api.mjs");
const existing = await apiJson("/api/v1/admin/cards?limit=1");
assert.ok(Array.isArray(existing.items) && existing.items.length === 0, "CI fixture setup requires an empty catalogue; existing data is never reset.");

const fixtureDir = path.join(process.cwd(), ".foilbury/generated/_test");
// Brand uploads need different bytes from the seeded subject/background:
// storage keys currently depend on the hash, while deduplication includes kind.
const fixtureImages = [
  ["public/art/layers/mark-mono.png", "mark.png"],
  ["public/art/layers/card-back.png", "cover.png"],
  ["public/brand/discord-avatar.png", "test-card-subject.png"],
];
for (const [source, filename] of fixtureImages) {
  assert.ok(fs.existsSync(source), `Tracked fixture image is missing: ${source}`);
  assert.ok(!fs.existsSync(path.join(fixtureDir, filename)), "CI fixture files already exist; use a fresh CI checkout.");
}
assert.ok(fs.existsSync("public/brand/card-back.webp"), "Tracked card-back fixture is missing.");
fs.mkdirSync(fixtureDir, { recursive: true });
for (const [source, filename] of fixtureImages) {
  fs.copyFileSync(source, path.join(fixtureDir, filename), fs.constants.COPYFILE_EXCL);
}

async function uploadFixture(kind, file) {
  const form = new FormData();
  form.append("file", new Blob([fs.readFileSync(file)], { type: "image/png" }), path.basename(file));
  form.append("kind", kind);
  form.append("name", `Synthetic CI ${kind}`);
  form.append("credit", "Foilbury tracked brand artwork, reused as a local CI fixture.");
  form.append("sourcePath", file);
  const result = await apiForm("/api/v1/admin/assets", form);
  assert.ok(result.asset?.id, `The ${kind} fixture upload did not return an asset.`);
  return result.asset.id;
}

const subjectAssetId = await uploadFixture("subject", "public/art/layers/mark.png");
const backgroundAssetId = await uploadFixture("background", "public/art/layers/material-plain.png");

const collections = await apiJson("/api/v1/admin/collections");
const publicCollection = collections.items.find((collection) => collection.slug === "bubbles");
assert.ok(publicCollection?.id && publicCollection.scope === "global", "The bootstrap Bubbles collection is missing.");
await apiJson(`/api/v1/admin/collections/${publicCollection.id}`, {
  method: "PATCH",
  body: {
    name: "Bubbles (synthetic CI showcase)",
    description: "Public visibility fixture using tracked Foilbury brand artwork.",
    status: "published",
    viewAudience: "public",
  },
});
const memberCollection = await apiJson("/api/v1/admin/collections", {
  method: "POST",
  body: {
    slug: "nba-opening-night",
    name: "NBA privacy sentinel (synthetic CI)",
    description: "Synthetic member-visibility fixture. Contains no launch roster or third-party artwork.",
    scope: "global",
    status: "published",
    viewAudience: "members",
  },
});
assert.ok(memberCollection.collection?.id, "The member collection fixture was not created.");
await apiJson(`/api/v1/admin/collections/${memberCollection.collection.id}/enable`, { method: "POST", body: { enabled: true } });

const fixtures = [
  { slug: "tux", name: "Tux (synthetic CI sentinel)", collectionSlug: "bubbles" },
  { slug: "shai-gilgeous-alexander", name: "Shai Gilgeous-Alexander (synthetic CI sentinel)", collectionSlug: "nba-opening-night" },
];
for (const fixture of fixtures) {
  const created = await apiJson("/api/v1/admin/cards", {
    method: "POST",
    body: {
      ...fixture,
      logicalId: `ci-privacy:${fixture.slug}`,
      subtitle: "Synthetic browser-test fixture",
      description: "This synthetic record tests public and member access. Its image is Foilbury brand artwork.",
      bio: "No character or player biography is supplied. This record is an isolated CI test sentinel.",
      bioSafe: "Synthetic CI privacy test record.",
      sourceWork: "Foilbury CI fixtures",
      reviewStatus: "reviewed",
      rarityKey: "rare",
    },
  });
  assert.ok(created.card?.id, `Card fixture ${fixture.slug} was not created.`);
  fixture.id = created.card.id;
  const edition = await apiJson(`/api/v1/admin/cards/${fixture.id}/editions`, {
    method: "POST",
    body: {
      name: "Synthetic CI edition",
      subjectAssetId,
      backgroundAssetId,
      materials: ["plain"],
      effects: ["none"],
      status: "published",
    },
  });
  fixture.variantId = edition.card?.editions.flatMap((item) => item.variants)[0]?.id;
  assert.ok(fixture.variantId, `Card fixture ${fixture.slug} has no variant.`);
  await apiJson(`/api/v1/admin/cards/${fixture.id}/status`, { method: "POST", body: { status: "published" } });
}

// Complete the real local render jobs before browser scripts use their bounded
// queues. Distinct names produce distinct front bytes for the two audiences.
const rendered = spawnSync(process.execPath, ["scripts/render-cards.mjs", "--limit=2"], {
  cwd: process.cwd(),
  stdio: "inherit",
  timeout: 180000,
});
assert.equal(rendered.status, 0, `CI fixture rendering failed: ${rendered.error?.message ?? rendered.signal ?? "non-zero exit"}`);

// A real member back ensures test-privacy's conditional back-URL check executes.
const memberFixture = fixtures.find((fixture) => fixture.collectionSlug === "nba-opening-night");
const back = new FormData();
back.append("back", new Blob([fs.readFileSync("public/brand/card-back.webp")], { type: "image/webp" }), "ci-member-back.webp");
await apiForm(`/api/v1/admin/variants/${memberFixture.variantId}/back`, back);

const pool = await apiJson("/api/v1/admin/pools", {
  method: "POST",
  body: {
    slug: "cabinet-draw",
    name: "Synthetic CI capsule",
    description: "Local privacy-test pool containing only synthetic fixtures.",
    price: 0,
    entries: fixtures.map((fixture) => ({ variantId: fixture.variantId, weight: 1 })),
  },
});
assert.ok(pool.pool?.id, "The synthetic pool was not created.");
await apiJson(`/api/v1/admin/pools/${pool.pool.id}/publish`, { method: "POST", body: {} });
await apiJson("/api/v1/admin/catalogue/publish", { method: "POST", body: {} });

const ready = await apiJson("/api/v1/admin/cards?limit=200");
for (const fixture of fixtures) {
  const card = ready.items.find((item) => item.id === fixture.id);
  const variant = card?.editions.flatMap((edition) => edition.variants).find((item) => item.id === fixture.variantId);
  assert.equal(card?.status, "published");
  assert.ok(variant?.render_url, `Card fixture ${fixture.slug} has no front render.`);
  if (fixture === memberFixture) assert.ok(variant.back_render_url, "The member fixture must exercise the back-media privacy check.");
}
const search = await apiJson("/api/v1/catalogue?search=Shai");
assert.ok(search.items.some((card) => card.id === memberFixture.id), "The member search sentinel is missing; anonymous search checks would be vacuous.");

fs.writeFileSync(path.join(process.cwd(), ".foilbury/ci-fixtures.json"), JSON.stringify({
  scope: "synthetic local CI fixtures",
  generated_at: new Date().toISOString(),
  cards: fixtures,
  album_uploads: fixtureImages.map(([, filename]) => path.join(".foilbury/generated/_test", filename)),
}, null, 2) + "\n");
console.log("Synthetic local CI fixtures ready: two rendered cards, one member back, one pool and three album upload files.");
