import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createServer } from 'vite';
import { chromium } from '@playwright/test';

test('gift recovery survives an ambiguous send and a reload', async (t) => {
  const root=process.cwd(), dir=fs.mkdtempSync(path.join(os.tmpdir(),'foilbury-gift-ui-'));
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  fs.symlinkSync(path.join(root,'node_modules'),path.join(dir,'node_modules'));
  fs.writeFileSync(path.join(dir,'index.html'),'<div id="root"></div><script type="module" src="/entry.jsx"></script>');
  fs.writeFileSync(path.join(dir,'entry.jsx'),`import React from 'react';import {createRoot} from 'react-dom/client';import GiftComposer from '/@fs${path.join(root,'src/components/admin/GiftComposer.tsx')}';window.__FOILBURY_STUDIO__=true;createRoot(document.getElementById('root')).render(<GiftComposer platformAdmin={false}/>);`);
  const server=await createServer({configFile:false,root:dir,cacheDir:path.join(dir,"vite-cache"),esbuild:{jsx:'automatic'},resolve:{alias:{'@':path.join(root,'src')}},server:{host:'127.0.0.1',port:0,fs:{allow:[root,dir]}}});
  t.after(()=>server.close());await server.listen();
  const browser=await chromium.launch({headless:true});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:375,height:800}});
  let sentKey=''; let rejectCode=''; const sentKeys=[]; let secondSent; const secondSend=new Promise((resolve)=>{secondSent=resolve;});
  await page.route('**/api/v1/studio/**',async route=>{
    const request=route.request(),url=new URL(request.url()),name=url.pathname;
    let body={items:[]};
    if(name.endsWith('/gifts/policy')) body={per_recipient_foil:100,self_grants_allowed:false};
    if(name.endsWith('/members')) body={items:[{id:'member-1',email:'member@example.test',display_name:'Member One',role:'player'}]};
    if(name.endsWith('/gifts/preview')) body={recipient_count:1,recipient_digest:'a'.repeat(64),sample:[{user_id:'member-1',display_name:'Member One',tenant_name:'Test'}],per_recipient_foil:480,total_foil:480,openings_per_recipient:0,standard_opening_price:80,standard_opening_revision:1,message:null,limits:{max_recipients:500,per_recipient_foil:100,self_grants_allowed:false}};
    if(name.endsWith('/gifts') && request.method()==='POST') {if(rejectCode)return route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({error:{code:rejectCode,message:rejectCode==='recipient_invalid'?'The selected recipient is no longer active.':'The recipient roster changed. Preview again.'}})});sentKey=request.headers()['idempotency-key'];sentKeys.push(sentKey);if(sentKeys.length===2) secondSent();return route.abort('connectionreset');}
    if(name.includes('/gifts/recovery/')) {assert.equal(decodeURIComponent(name.split('/').at(-1)),sentKey);body={found:true,campaign:{id:'fixture-campaign',status:'completed',sent_count:1,pending_count:0}};}
    return route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(body)});
  });
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`);
  await page.getByText('Member One').first().waitFor();
  await page.getByText(/Your current limit is 100 Foil per recipient/).waitFor();
  await page.getByText(/Self-gifts are not enabled/).waitFor();
  assert.equal(await page.getByLabel('Foil per recipient').inputValue(),'100');
  await page.getByLabel(/Member One/).check();
  await page.getByPlaceholder('e.g. Community night thank-you').fill('Fixture gift');
  await page.getByRole('button',{name:/preview/i}).click();
  await page.getByText('Ready to send').waitFor();
  await page.getByRole('button',{name:/send gift/i}).click();
  await page.getByRole('button',{name:'Check pending gift'}).waitFor();
  assert.ok(sentKey.startsWith('gift-'));
  await page.getByRole('button',{name:/send gift/i}).click();
  await secondSend;
  assert.deepEqual(sentKeys,[sentKey,sentKey]);
  rejectCode='recipient_invalid';
  await page.getByRole('button',{name:/send gift/i}).click();
  await page.getByText(/selected recipient is no longer active/i).waitFor();
  assert.ok(await page.evaluate(()=>sessionStorage.getItem('foilbury.pending-gift')));
  rejectCode='';
  await page.reload();
  await page.getByRole('button',{name:'Check pending gift'}).click();
  await page.getByText(/Recovered campaign fixture-campaign/).waitFor();
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('foilbury.pending-gift')),null);
  rejectCode='gift_recipients_changed';
  await page.getByLabel(/Member One/).check();
  await page.getByPlaceholder('e.g. Community night thank-you').fill('New fixture gift');
  await page.getByRole('button',{name:/preview/i}).click();
  await page.getByText('Ready to send').waitFor();
  await page.getByRole('button',{name:/send gift/i}).click();
  await page.getByText(/recipient roster changed/i).waitFor();
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('foilbury.pending-gift')),null);
  assert.equal(await page.getByRole('button',{name:/preview/i}).isEnabled(),true);
  rejectCode='recipient_invalid';
  await page.getByRole('button',{name:/preview/i}).click();
  await page.getByText('Ready to send').waitFor();
  await page.getByRole('button',{name:/send gift/i}).click();
  await page.getByText(/selected recipient is no longer active/i).waitFor();
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('foilbury.pending-gift')),null);
  assert.equal(await page.getByRole('button',{name:/preview/i}).isEnabled(),true);
});
