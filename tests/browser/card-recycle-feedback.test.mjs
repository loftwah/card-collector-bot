import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createServer } from "vite";
import { chromium } from "@playwright/test";
import tailwindcss from "@tailwindcss/vite";
import AxeBuilder from "@axe-core/playwright";

test("recycle uncertainty retains the same request across tab closure and timeout", async (t) => {
  const root = process.cwd();
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), "foilbury-recycle-browser-"));
  t.after(() => fs.rmSync(fixture, { recursive: true, force: true }));
  fs.symlinkSync(path.join(root, "node_modules"), path.join(fixture, "node_modules"));
  fs.writeFileSync(path.join(fixture,'fixture.css'),fs.readFileSync(path.join(root,'src/styles/global.css'),'utf8').replace('@import "tailwindcss";',`@import "tailwindcss";\n@source ${JSON.stringify(path.join(root,'src'))};`));
  fs.writeFileSync(path.join(fixture, "index.html"), '<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1"></head><body><div id="root"></div><script type="module" src="/entry.jsx"></script></body></html>');
  const component = `/@fs${path.join(root, "src/components/player/CardDetailActions.tsx")}`;
  fs.writeFileSync(path.join(fixture, "entry.jsx"), `import React from 'react'; import {createRoot} from 'react-dom/client'; import '/fixture.css'; import CardDetailActions from ${JSON.stringify(component)}; createRoot(document.getElementById('root')).render(<CardDetailActions instanceId="fixture-instance" tenantId="fixture-tenant" userId="fixture-user" cardId="fixture-card" initialFavourite={false} initialLocked={false} initialWishlist={false} reserved={false} />);`);
  const server = await createServer({ root: fixture, cacheDir:path.join(fixture,"vite-cache"), configFile: false, plugins:[tailwindcss()], logLevel: "silent", esbuild: { jsx: "automatic" }, resolve: { alias: { "@": path.join(root, "src") } }, server: { host: "127.0.0.1", port: 0, fs: { allow: [root, fixture] } } });
  t.after(() => server.close());
  await server.listen();
  const address = server.httpServer.address();
  assert.ok(address && typeof address === "object");
  const browser = await chromium.launch({ headless: true });
  t.after(() => browser.close());
  const context=await browser.newContext({viewport:{width:375,height:667}});
  let page = await context.newPage();
  let commits = 0;
  let previews = 0;
  const keys=[];
  let hang = false;
  let responseMode='failure';
  let cancelMode='cancelled';const cancelKeys=[];
  let releaseHang;
  const hungResponse = new Promise((resolve) => { releaseHang = resolve; });
  let releaseResponse;
  const pendingResponse = new Promise((resolve) => { releaseResponse = resolve; });
  await context.route("**/api/v1/recycle/preview", (route) => {previews++;return route.fulfill({ json: { credit: 100, breakdown: { rarity: 60, material: 40 }, currency_symbol: "✦", warning: "This cannot be undone." } });});
  await context.route("**/api/v1/recycle", async (route) => { commits++; keys.push(route.request().headers()['idempotency-key']); if(responseMode==='invalid')return route.fulfill({status:200,json:{}}); if(responseMode==='success')return route.fulfill({status:200,json:{receipt_id:'receipt-fixture',instance_id:'fixture-instance',credit:100,balance_after:100}}); await (hang ? hungResponse : pendingResponse); return route.fulfill({ status: 503, json: { error: { message: "Fixture recycle failure" } } }).catch(() => {}); });
  await context.route('**/api/v1/recycle/cancel',route=>{cancelKeys.push(route.request().headers()['idempotency-key']);if(cancelMode==='failure')return route.fulfill({status:503,json:{error:{message:'Cancellation not confirmed'}}});return route.fulfill({json:cancelMode==='cancelled'?{status:'cancelled'}:{status:'completed',receipt:{receipt_id:'receipt-fixture',instance_id:'fixture-instance',credit:100,balance_after:100}}});});
  await page.clock.install();
  await page.goto(`http://127.0.0.1:${address.port}/`);
  await page.getByRole("button", { name: "Recycle", exact: true }).click();
  let dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Recycle permanently" }).click();
  await dialog.getByRole("button", { name: "Recycling…" }).waitFor();
  await page.keyboard.press("Escape");
  assert.equal(await dialog.isVisible(), true);
  releaseResponse();
  await dialog.getByRole("alert").getByText("Fixture recycle failure").waitFor();
  assert.equal(await dialog.getByRole("button", { name: "Retry same request" }).isEnabled(), true);
  assert.equal(await dialog.getByRole("link", { name: "Check your collection" }).getAttribute("href"), "/play/collection");
  assert.equal(commits, 1);
  await page.setViewportSize({width:320,height:667});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await dialog.getByRole('button',{name:'Retry same request'}).focus();
  assert.equal(await dialog.getByRole('button',{name:'Retry same request'}).evaluate(el=>document.activeElement===el),true);
  assert.deepEqual((await new AxeBuilder({page}).include('[role="dialog"]').analyze()).violations,[]);
  const evidence=fs.mkdtempSync(path.join(root,'.foilbury/evidence/recycle-recovery-'));
  await page.screenshot({path:path.join(evidence,'mobile-uncertain.png')});
  await page.close();
  page=await context.newPage();await page.clock.install();
  await page.goto(`http://127.0.0.1:${address.port}/`);
  await page.getByRole("button", { name: "Recycle", exact: true }).click();
  dialog=page.getByRole('dialog');
  await page.getByRole("dialog").getByText(/previous recycle request has an unconfirmed result/).waitFor();
  assert.equal(previews,1);
  assert.equal(await page.getByRole("dialog").getByRole("button", { name: "Retry same request" }).isEnabled(), true);
  hang = true;
  const retrySent=page.waitForRequest(request=>request.url().endsWith('/api/v1/recycle') && request.method()==='POST');
  await page.getByRole("dialog").getByRole("button", { name: "Retry same request" }).click();
  await retrySent;
  await page.getByRole("dialog").getByRole("button", { name: "Recycling…" }).waitFor();
  await page.clock.fastForward(15_001);
  await page.getByRole("dialog").getByRole("alert").getByText("The request timed out before we could confirm the result.").waitFor();
  assert.equal(await page.getByRole("dialog").getByRole("button", { name: "Retry same request" }).isEnabled(), true);
  assert.equal(keys.length,2);
  assert.equal(keys[0],keys[1]);
  releaseHang();
  hang=false;responseMode='invalid';
  await dialog.getByRole('button',{name:'Retry same request'}).click();
  await dialog.getByRole('alert').getByText('The recycle receipt could not be confirmed.').waitFor();
  assert.equal(keys[2],keys[0]);
  responseMode='success';
  await dialog.getByRole('button',{name:'Retry same request'}).click();
  await page.waitForURL('**/play/collection');
  assert.equal(keys[3],keys[0]);
  assert.equal(await page.evaluate(async()=>{const db=await new Promise((resolve,reject)=>{const r=indexedDB.open('foilbury-recycle-recovery-v1',1);r.onsuccess=()=>resolve(r.result);r.onerror=()=>reject(r.error);});return await new Promise((resolve,reject)=>{const tx=db.transaction('pending','readonly'),r=tx.objectStore('pending').get(JSON.stringify(['fixture-tenant','fixture-user','fixture-instance']));r.onsuccess=()=>resolve(r.result??null);r.onerror=()=>reject(r.error);});}),null);
  responseMode='failure';await page.goto(`http://127.0.0.1:${address.port}/`);await page.getByRole('button',{name:'Recycle',exact:true}).click();dialog=page.getByRole('dialog');
  await dialog.getByRole('button',{name:'Recycle permanently'}).click();await dialog.getByRole('alert').getByText('Fixture recycle failure').waitFor();
  const cancelKey=keys.at(-1);await dialog.getByRole('button',{name:'Cancel pending request'}).click();
  assert.equal(cancelKeys.length,0);await dialog.getByText(/If it completed first/).waitFor();
  await page.setViewportSize({width:320,height:667});await dialog.getByRole('button',{name:'Confirm cancellation'}).focus();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  assert.deepEqual((await new AxeBuilder({page}).include('[role="dialog"]').analyze()).violations,[]);
  await page.screenshot({path:path.join(evidence,'mobile-cancel-confirm.png')});
  cancelMode='failure';await dialog.getByRole('button',{name:'Confirm cancellation'}).click();
  await dialog.getByRole('alert').getByText('Cancellation not confirmed').waitFor();
  cancelMode='cancelled';
  await dialog.getByRole('button',{name:'Confirm cancellation'}).click();
  await page.getByRole('status').getByText(/Recycle request cancelled/).waitFor();assert.equal(cancelKeys[0],cancelKey);assert.equal(cancelKeys[1],cancelKey);
  await page.getByRole('button',{name:'Recycle',exact:true}).click();dialog=page.getByRole('dialog');
  await dialog.getByRole('button',{name:'Recycle permanently'}).click();await dialog.getByRole('alert').getByText('Fixture recycle failure').waitFor();
  cancelMode='completed';await dialog.getByRole('button',{name:'Cancel pending request'}).click();await dialog.getByRole('button',{name:'Confirm cancellation'}).click();
  await page.waitForURL('**/play/collection');assert.equal(cancelKeys[2],keys.at(-1));
  const blocked=await context.newPage();
  await blocked.addInitScript(()=>Object.defineProperty(window,'indexedDB',{get(){throw new Error('blocked');}}));
  await blocked.goto(`http://127.0.0.1:${address.port}/`);
  await blocked.getByRole('alert').getByText(/Recovery could not be loaded/).waitFor();
  assert.equal(await blocked.getByRole('button',{name:'Recycle',exact:true}).isDisabled(),true);
});
