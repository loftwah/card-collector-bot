import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createServer } from "vite";
import { chromium } from "@playwright/test";

test("wishlist target persists Any finish and restores the previous value on failure", async (t) => {
  const root = process.cwd();
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), "foilbury-wishlist-browser-"));
  t.after(() => fs.rmSync(fixture, { recursive: true, force: true }));
  fs.symlinkSync(path.join(root, "node_modules"), path.join(fixture, "node_modules"));
  fs.writeFileSync(path.join(fixture, "index.html"), '<!doctype html><html><head><meta name="foilbury-csrf" content="fixture"></head><body><div id="root"></div><script type="module" src="/entry.jsx"></script></body></html>');
  const component = `/@fs${path.join(root, "src/components/player/CardDetailActions.tsx")}`;
  fs.writeFileSync(path.join(fixture, "entry.jsx"), `import React from 'react'; import {createRoot} from 'react-dom/client'; import CardDetailActions from ${JSON.stringify(component)}; const state = await (await fetch('/api/v1/wishlist')).json(); createRoot(document.getElementById('root')).render(<CardDetailActions instanceId="fixture-instance" tenantId="fixture-tenant" userId="fixture-user" cardId="fixture-card" initialFavourite={false} initialLocked={false} initialWishlist={true} initialWishlistTarget={state.target ?? ''} wishlistVariants={[{id:'fixture-plain',label:'Plain'}]} reserved={false} />);`);
  const server = await createServer({ root: fixture, configFile: false, logLevel: "silent", esbuild: { jsx: "automatic" }, resolve: { alias: { "@": path.join(root, "src") } }, server: { host: "127.0.0.1", port: 0, fs: { allow: [root, fixture] } } });
  t.after(() => server.close());
  await server.listen();
  const address = server.httpServer.address();
  assert.ok(address && typeof address === "object");
  const browser = await chromium.launch({ headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 375, height: 667 } });
  let target = "fixture-plain";
  let failNext = false;
  const bodies = [];
  await page.route("**/api/v1/wishlist", async (route) => {
    if (route.request().method() === "GET") return route.fulfill({ json: { target } });
    const body = route.request().postDataJSON();
    bodies.push(body);
    if (failNext) { failNext = false; return route.fulfill({ status: 503, json: { error: { message: "Fixture save failed" } } }); }
    target = body.targetVariantId;
    return route.fulfill({ json: { ok: true } });
  });
  await page.goto(`http://127.0.0.1:${address.port}/`);
  const select = page.getByRole("combobox", { name: "Wishlist finish or edition" });
  await select.waitFor();
  await select.selectOption("");
  await page.getByRole("status").getByText("Wishlist target updated to any finish.").waitFor();
  assert.equal(bodies.at(-1).targetVariantId, null);
  await page.reload();
  await select.waitFor();
  assert.equal(await select.inputValue(), "");
  await select.selectOption("fixture-plain");
  await page.getByRole("status").getByText("Wishlist target updated to that exact finish.").waitFor();
  assert.equal(bodies.at(-1).targetVariantId, "fixture-plain");
  await page.reload();
  await select.waitFor();
  assert.equal(await select.inputValue(), "fixture-plain");
  failNext = true;
  await select.selectOption("");
  await page.getByRole("alert").getByText("Fixture save failed").waitFor();
  assert.equal(await select.inputValue(), "fixture-plain");
  assert.equal(await page.getByRole("status").count(), 0);
  await page.getByRole("button", { name: "Wishlisted" }).click();
  await page.getByText("Choose a finish, then select Wishlist to save it.").waitFor();
  const savedRequests = bodies.length;
  await select.selectOption("");
  await select.selectOption("fixture-plain");
  assert.equal(bodies.length, savedRequests);
  await page.getByRole("button", { name: "Wishlist", exact: true }).click();
  await page.getByRole("status").getByText("Wishlist saved with the exact finish you chose.").waitFor();
  assert.equal(bodies.at(-1).targetVariantId, "fixture-plain");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
});
